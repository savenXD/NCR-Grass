// Builds responsive AVIF + WebP variants of every site photo as plain static files in public/img/
// (no /_next/image round trip, so a cold server never encodes anything on a visitor's first load).
// Sources: assets-source/images/<group>/<name>.{jpg,png}. Run: node scripts/build-images.mjs
// Writes public/img/<group>/<name>-<width>.{avif,webp} and src/lib/image-manifest.ts.
import sharp from "sharp"
import { mkdir, readdir, stat, writeFile } from "node:fs/promises"

const SRC = "assets-source/images"
const OUT = "public/img"

// Widths per group: roughly CSS width x 1x/1.5x/2x for the slot the photo is shown in
const groups = {
  services: { widths: [320, 480, 640, 800, 1024], avif: { quality: 50, effort: 6 }, webp: { quality: 78, effort: 6 } },
  "who-we-serve": { widths: [480, 720, 960, 1280], avif: { quality: 40, effort: 6 }, webp: { quality: 66, effort: 6 } },
  "why-choose-us": { widths: [480, 720, 960, 1280], avif: { quality: 40, effort: 6 }, webp: { quality: 66, effort: 6 } },
  about: { widths: [280, 440], avif: { quality: 42, effort: 6 }, webp: { quality: 68, effort: 6 } },
  // Any aspect ratio, any count: drop files in assets-source/images/gallery and run `npm run images`
  gallery: { widths: [400, 640, 960, 1280, 1600], avif: { quality: 45, effort: 6 }, webp: { quality: 72, effort: 6 } },
  owner: { widths: [360, 560, 800, 1120], avif: { quality: 48, effort: 6 }, webp: { quality: 74, effort: 6 } },
}

// Incremental: a variant is rebuilt only if it is missing or older than its source (delete public/img to force a full rebuild)
const fresh = async (out, src) => {
  try {
    return (await stat(out)).mtimeMs > (await stat(src)).mtimeMs
  } catch {
    return false
  }
}
const manifest = {}
let total = 0

for (const [group, cfg] of Object.entries(groups)) {
  await mkdir(`${OUT}/${group}`, { recursive: true })
  for (const file of (await readdir(`${SRC}/${group}`)).filter((f) => /\.(jpe?g|png|webp|avif|tiff?)$/i.test(f)).sort()) {
    const name = file.replace(/\.[^.]+$/, "")
    const input = sharp(`${SRC}/${group}/${file}`)
    const { width: W, height: H, hasAlpha } = await input.metadata()
    const widths = cfg.widths.filter((w) => w <= W)
    if (!widths.length || widths[widths.length - 1] < W) widths.push(Math.min(W, cfg.widths.at(-1)))
    for (const w of [...new Set(widths)]) {
      for (const ext of ["avif", "webp"]) {
        const out = `${OUT}/${group}/${name}-${w}.${ext}`
        if (await fresh(out, `${SRC}/${group}/${file}`)) continue
        const buf = await sharp(`${SRC}/${group}/${file}`).resize({ width: w }).toFormat(ext, cfg[ext]).toBuffer()
        await writeFile(out, buf)
        total += buf.length
      }
    }
    // Tiny blurred preview shown as the background until the photo arrives (skipped for cut-outs with transparency)
    const blur = hasAlpha ? null : `data:image/webp;base64,${(await sharp(`${SRC}/${group}/${file}`).resize({ width: 16 }).webp({ quality: 40 }).toBuffer()).toString("base64")}`
    manifest[`${group}/${name}`] = { w: W, h: H, widths: [...new Set(widths)], blur }
  }
}

await writeFile(
  "src/lib/image-manifest.ts",
  `// Generated by scripts/build-images.mjs. Do not edit.\nexport type ImageEntry = { w: number; h: number; widths: number[]; blur: string | null }\nexport const imageManifest: Record<string, ImageEntry> = ${JSON.stringify(manifest, null, 2)}\n`
)
console.log(`${Object.keys(manifest).length} images, ${(total / 1024) | 0} KB newly written`)
