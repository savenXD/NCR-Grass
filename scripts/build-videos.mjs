// Compresses gallery clips for the web. Sources: assets-source/videos/gallery/*.{mp4,mov,webm}. Run: npm run videos
// Writes public/video/gallery/<name>.mp4 (H.264, max 720p, muted, faststart so it plays before fully downloaded),
// <name>-poster.webp (first-second frame) and src/lib/video-manifest.ts. Needs ffmpeg on PATH.
import sharp from "sharp"
import { execFileSync } from "node:child_process"
import { mkdir, readdir, stat, writeFile } from "node:fs/promises"

const SRC = "assets-source/videos/gallery"
const OUT = "public/video/gallery"
await mkdir(OUT, { recursive: true })

const fresh = async (out, src) => {
  try {
    return (await stat(out)).mtimeMs > (await stat(src)).mtimeMs
  } catch {
    return false
  }
}
const manifest = {}

for (const file of (await readdir(SRC)).filter((f) => /\.(mp4|mov|m4v|webm)$/i.test(f)).sort()) {
  const name = file.replace(/\.[^.]+$/, "")
  const src = `${SRC}/${file}`
  const mp4 = `${OUT}/${name}.mp4`
  const poster = `${OUT}/${name}-poster.webp`
  if (!(await fresh(mp4, src))) {
    execFileSync("ffmpeg", ["-y", "-v", "error", "-i", src, "-an", "-vf", "scale='min(1280,iw)':-2,fps=30", "-c:v", "libx264", "-preset", "slow", "-crf", "28", "-pix_fmt", "yuv420p", "-profile:v", "main", "-movflags", "+faststart", mp4])
  }
  if (!(await fresh(poster, mp4))) {
    const png = execFileSync("ffmpeg", ["-v", "error", "-ss", "0.5", "-i", mp4, "-frames:v", "1", "-f", "image2pipe", "-vcodec", "png", "-"], { maxBuffer: 1 << 28 })
    await writeFile(poster, await sharp(png).webp({ quality: 70, effort: 6 }).toBuffer())
  }
  const { width: w, height: h } = await sharp(poster).metadata()
  manifest[name] = { w, h, kb: ((await stat(mp4)).size / 1024) | 0 }
}

await writeFile(
  "src/lib/video-manifest.ts",
  `// Generated by scripts/build-videos.mjs. Do not edit.\nexport type VideoEntry = { w: number; h: number; kb: number }\nexport const videoManifest: Record<string, VideoEntry> = ${JSON.stringify(manifest, null, 2)}\n`
)
console.log(Object.entries(manifest).map(([n, v]) => `${n} ${v.w}x${v.h} ${v.kb} KB`).join("\n"))
