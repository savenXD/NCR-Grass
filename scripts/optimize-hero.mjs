// Builds the hero image variants served as plain static files (no image-optimizer round trip on first visit).
// Source: assets-source/home-screen.png. Run: node scripts/optimize-hero.mjs
import sharp from "sharp"
import { mkdir, writeFile } from "node:fs/promises"

const SRC = "assets-source/home-screen.png"
const OUT = "public/images/hero"
await mkdir(OUT, { recursive: true })

const { width: W, height: H } = await sharp(SRC).metadata()

// Phones show a tall, narrow slice of the photo (the house side). Crop it at native resolution
// instead of downscaling the whole landscape picture and stretching it.
const cropW = Math.round(H * 0.62)
const cropX = Math.round(0.2 * (W - cropW))
const mobile = () => sharp(SRC).extract({ left: cropX, top: 0, width: cropW, height: H })
const desktop = () => sharp(SRC)

const sizes = {}
for (const [name, make] of [["mobile", mobile], ["desktop", desktop]]) {
  for (const [ext, opts] of [
    ["avif", { quality: 36, effort: 6 }],
    ["webp", { quality: 55, effort: 6 }],
  ]) {
    const buf = await make()[ext](opts).toBuffer()
    await writeFile(`${OUT}/hero-${name}.${ext}`, buf)
    sizes[`${name}.${ext}`] = buf.length
  }
}
console.log(sizes, { mobile: [cropW, H], desktop: [W, H] })

// Tiny blurred previews, inlined as CSS backgrounds until the real photo arrives
const blur = async (img) => `data:image/webp;base64,${(await img.resize({ width: 24 }).webp({ quality: 40 }).toBuffer()).toString("base64")}`
await writeFile(
  "src/lib/hero-blur.ts",
  `// Generated by scripts/optimize-hero.mjs. Do not edit.\nexport const heroBlur = {\n  mobile: "${await blur(mobile())}",\n  desktop: "${await blur(desktop())}",\n  mobileSize: [${cropW}, ${H}],\n  desktopSize: [${W}, ${H}],\n} as const\n`
)
